"""Synchronous structural interfaces. No persistence implementation belongs here."""
from datetime import date
from types import TracebackType
from typing import Protocol

from .dto import (
    Alert, AlertQuery, Assessment, AssessmentQuery, Astronaut, AstronautQuery,
    CheckinQuery, CommandReceipt, DailyCheckin, EnvironmentalReading,
    EnvironmentalReadingQuery, HealthReading, HealthReadingQuery, Mission,
    MissionQuery, Page, ReadinessResult, SimulationRun, SimulationRunQuery, UUIDString,
)
from .enums import EnvironmentalIndicator, HealthIndicator, Source


class MissionRepository(Protocol):
    def get(self, id: UUIDString) -> Mission | None: ...
    def list(self, query: MissionQuery) -> Page[Mission]: ...
    def add(self, record: Mission) -> Mission: ...


class AstronautRepository(Protocol):
    def get(self, id: UUIDString) -> Astronaut | None: ...
    def list(self, query: AstronautQuery) -> Page[Astronaut]: ...
    def add(self, record: Astronaut) -> Astronaut: ...


class CheckinRepository(Protocol):
    def get(self, id: UUIDString) -> DailyCheckin | None: ...
    def get_for_date(self, astronaut_id: UUIDString, date: date) -> DailyCheckin | None: ...
    def list(self, astronaut_id: UUIDString, query: CheckinQuery) -> Page[DailyCheckin]: ...
    def add(self, record: DailyCheckin) -> DailyCheckin: ...


class HealthReadingRepository(Protocol):
    def add_many(self, records: list[HealthReading]) -> list[HealthReading]: ...
    def list(self, astronaut_id: UUIDString, query: HealthReadingQuery) -> Page[HealthReading]: ...
    def latest_by_indicator(self, astronaut_id: UUIDString, source: Source | None = None) -> dict[HealthIndicator, HealthReading]: ...


class EnvironmentalReadingRepository(Protocol):
    def add_many(self, records: list[EnvironmentalReading]) -> list[EnvironmentalReading]: ...
    def list(self, mission_id: UUIDString, query: EnvironmentalReadingQuery) -> Page[EnvironmentalReading]: ...
    def latest_by_indicator(self, mission_id: UUIDString) -> dict[EnvironmentalIndicator, EnvironmentalReading]: ...


class AssessmentRepository(Protocol):
    def get(self, id: UUIDString) -> Assessment | None: ...
    def get_by_fingerprint(self, astronaut_id: UUIDString, ruleset_version: str, fingerprint: str) -> Assessment | None: ...
    def list(self, astronaut_id: UUIDString, query: AssessmentQuery) -> Page[Assessment]: ...
    def add(self, record: Assessment) -> Assessment: ...


class AlertRepository(Protocol):
    def get(self, id: UUIDString) -> Alert | None: ...
    def list(self, astronaut_id: UUIDString, query: AlertQuery) -> Page[Alert]: ...
    def get_open(self, astronaut_id: UUIDString, rule_id: str) -> Alert | None: ...
    def add(self, record: Alert) -> Alert: ...
    def update(self, record: Alert) -> Alert: ...


class SimulationRunRepository(Protocol):
    def get(self, id: UUIDString) -> SimulationRun | None: ...
    def get_active(self) -> SimulationRun | None: ...
    def list(self, query: SimulationRunQuery) -> Page[SimulationRun]: ...
    def add(self, record: SimulationRun) -> SimulationRun: ...
    def update(self, record: SimulationRun, expected_last_tick: int) -> SimulationRun: ...


class CommandReceiptRepository(Protocol):
    def get(self, command_id: UUIDString) -> CommandReceipt | None: ...
    def add(self, record: CommandReceipt) -> CommandReceipt: ...


class UnitOfWork(Protocol):
    missions: MissionRepository
    astronauts: AstronautRepository
    checkins: CheckinRepository
    health_readings: HealthReadingRepository
    environmental_readings: EnvironmentalReadingRepository
    assessments: AssessmentRepository
    alerts: AlertRepository
    simulation_runs: SimulationRunRepository
    command_receipts: CommandReceiptRepository

    def __enter__(self) -> "UnitOfWork": ...
    def __exit__(self, exc_type: type[BaseException] | None, exc_value: BaseException | None, traceback: TracebackType | None) -> None: ...
    def commit(self) -> None: ...
    def rollback(self) -> None: ...


class AdapterFactory(Protocol):
    def create_uow(self) -> UnitOfWork: ...
    def check_ready(self) -> ReadinessResult: ...
